import test from "ava";
import { githubSlug, readmeSummary } from "../.ai/scripts/llms.js";
import { isPointer, manifestDirs } from "../.ai/scripts/inventory.js";
import {
  renderCopilot,
  renderCursor,
  splitGlobs,
} from "../.ai/scripts/sync.js";
import { parseFrontmatter } from "../.ai/scripts/lib.js";
import { validateAll } from "../.ai/scripts/validate.js";
import { sync } from "../.ai/scripts/sync.js";
import { runInventory } from "../.ai/scripts/inventory.js";
import { runLlms } from "../.ai/scripts/llms.js";

const rule = {
  name: "demo",
  data: { description: "Demo rule", globs: "a/**, b/**" },
  body: "\nBody\n",
};

test("splitGlobs trims and drops empties", (t) => {
  t.deepEqual(splitGlobs("a/**, b/** ,"), ["a/**", "b/**"]);
  t.deepEqual(splitGlobs(undefined), []);
});

test("renderCopilot and renderCursor include globs and a generated banner", (t) => {
  const copilot = renderCopilot(rule);
  t.true(copilot.includes('applyTo: "a/**,b/**"'));
  t.true(copilot.includes("GENERATED by .ai/scripts/sync.js"));
  const cursor = renderCursor(rule);
  t.true(cursor.includes("globs: a/**,b/**"));
  t.true(cursor.includes("alwaysApply: false"));
});

test("githubSlug matches GitHub anchors", (t) => {
  t.is(githubSlug("Quick `Start` Guide!"), "quick-start-guide");
});

test("readmeSummary extracts the intro and H2 headings", (t) => {
  const { sections } = readmeSummary(
    "# Title\n\nIntro text.\n\n## Install\n\n```\n## not a heading\n```\n\n## Usage\n",
  );
  t.deepEqual(sections, ["Install", "Usage"]);
});

test("isPointer accepts only short AGENTS.md pointers", (t) => {
  t.true(isPointer("<!-- c -->\n\nSee [AGENTS.md](AGENTS.md).\n"));
  t.false(isPointer("# Title\n\nline\n\nmore\n\nAGENTS.md\n"));
  t.false(isPointer("Some unrelated text\n"));
});

test("manifestDirs lists package dirs and ignores node_modules and .proto", (t) => {
  t.deepEqual(
    manifestDirs([
      "package.json",
      "tools/a/package.json",
      "sdk/core/Cargo.toml",
      "tools/a/node_modules/x/package.json",
      ".proto/tools/package.json",
    ]),
    ["sdk/core", "tools/a"],
  );
});

test("parseFrontmatter reads key/value pairs", (t) => {
  const { data, body } = parseFrontmatter(
    "---\nname: x\ndescription: y\n---\nBody",
  );
  t.is(data.name, "x");
  t.is(data.description, "y");
  t.true(body.includes("Body"));
});

test("repository AI resources are valid and generated files are current", (t) => {
  t.deepEqual(validateAll(), []);
});

test("sync, inventory, and llms checks report no drift", (t) => {
  t.notThrows(() => {
    for (const fn of [sync, runInventory, runLlms]) {
      const result = fn({ check: true });
      if (result && result.ok === false) throw new Error("drift detected");
    }
  });
});

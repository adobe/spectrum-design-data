// Usage: node generate.mjs [path/to/design-data] > switch.css
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const cli = process.argv[2] ?? "design-data";
const sizes = ["s", "m", "l", "xl"];
const schemes = ["light", "dark"];
const stateList = ["hover", "down", "keyboard-focus"];

const jobs = [];
for (const colorScheme of schemes)
  for (const size of sizes)
    for (const selected of [false, true])
      for (const emphasized of [false, true])
        for (const disabled of [false, true])
          for (const state of disabled ? [null] : [null, ...stateList])
            jobs.push({
              id: [
                colorScheme,
                size,
                +selected,
                +emphasized,
                +disabled,
                state ?? "base",
              ].join("_"),
              component: "switch",
              size,
              colorScheme,
              states: state ? [state] : [],
              options: {
                isSelected: selected,
                isEmphasized: emphasized,
                isDisabled: disabled,
              },
              meta: {
                colorScheme,
                size,
                selected,
                emphasized,
                disabled,
                state,
              },
            });

const dir = mkdtempSync(join(tmpdir(), "ui-sdk-switch-"));
const batch = join(dir, "batch.json");
writeFileSync(batch, JSON.stringify(jobs.map(({ meta, ...j }) => j)));
execFileSync(cli, ["render", "--batch", batch, "--out", dir, "--strict"], {
  stdio: ["ignore", "ignore", "inherit"],
});

const px = (n) => `${+n.toFixed(3)}px`;
const node = (scene, part) => scene.nodes.find((n) => n.part === part);

// Resolved declarations for one scene, keyed by ui-sdk part.
function declarations(scene) {
  const track = node(scene, "track");
  const handle = node(scene, "handle");
  const label = node(scene, "label");
  const ring = node(scene, "focus-indicator");
  const container = node(scene, "container");
  const border = track.stroke_width;
  return {
    root: {
      width: px(track.w),
      height: px(track.h),
      "border-radius": px(track.radius),
      background: track.fill,
      "border-color": track.stroke ?? "transparent",
      "border-width": px(border),
      outline: ring ? `${px(ring.stroke_width)} solid ${ring.stroke}` : "none",
      "outline-offset": ring
        ? px((ring.w - track.w) / 2 - ring.stroke_width)
        : "0",
    },
    thumb: {
      width: px(handle.w),
      height: px(handle.h),
      "border-radius": px(handle.radius),
      background: handle.fill,
      translate: `${px(handle.x - track.x - border)} 0`,
    },
    label: {
      "font-size": px(label.font_size),
      "font-weight": label.font_weight ?? 400,
      color: label.color,
      gap: px(
        container.tokens
          .find((t) => t.prop === "gap")
          ?.value.replace("px", "") * 1,
      ),
      "min-height": px(container.h),
    },
  };
}

const parts = {
  root: '[data-slot="switch"]',
  thumb: '[data-slot="switch-thumb"]',
  label: 'label:has(> [data-slot="switch"])',
};
const stateSelector = {
  hover: ":hover",
  down: ":active",
  "keyboard-focus": ":focus-visible",
};
// Later in the file wins at equal specificity, so hover precedes down precedes focus.
const stateOrder = [null, "hover", "down", "keyboard-focus"];

const scenes = new Map(
  jobs.map((j) => [
    j.id,
    JSON.parse(readFileSync(join(dir, `${j.id}.scene.json`), "utf8")),
  ]),
);
const decls = new Map([...scenes].map(([id, s]) => [id, declarations(s)]));

const out = [
  "/* Generated by tools/ui-sdk-spike/generate.mjs from the Switch visual recipe. Do not edit. */",
  '[data-slot="switch"] { box-sizing: border-box; display: inline-flex; align-items: center; flex: none; padding: 0; border-style: solid; cursor: pointer; }',
  '[data-slot="switch"][data-disabled] { cursor: default; }',
  '[data-slot="switch-thumb"] { display: block; flex: none; }',
  'label:has(> [data-slot="switch"]) { display: inline-flex; align-items: center; }',
  'label:has(> [data-slot="switch"]) > [data-slot="switch"] { flex: none; }',
];

const attrs = (m) =>
  [
    `[data-size="${m.size}"]`,
    m.selected ? "[data-checked]" : "[data-unchecked]",
    m.emphasized
      ? '[data-variant="emphasized"]'
      : ':not([data-variant="emphasized"])',
    m.disabled ? "[data-disabled]" : ":not([data-disabled])",
  ].join("");

for (const colorScheme of schemes) {
  const prefix =
    colorScheme === "dark" ? ':root[data-color-scheme="dark"] ' : "";
  for (const state of stateOrder)
    for (const j of jobs.filter(
      (j) => j.meta.colorScheme === colorScheme && j.meta.state === state,
    )) {
      const base = state ? decls.get(j.id.replace(`_${state}`, "_base")) : null;
      for (const [part, props] of Object.entries(decls.get(j.id))) {
        const changed = Object.entries(props).filter(
          ([k, v]) => !base || base[part][k] !== v,
        );
        if (!changed.length) continue;
        // Label lives outside the switch, so its state selectors go on the switch via :has().
        const m = j.meta;
        const sw = `[data-slot="switch"]${attrs(m)}${state ? stateSelector[state] : ""}`;
        const sel =
          part === "label"
            ? `${prefix}label:has(> ${sw})`
            : part === "root"
              ? `${prefix}${sw}`
              : `${prefix}${sw} > ${parts.thumb}`;
        out.push(
          `${sel} { ${changed.map(([k, v]) => `${k}: ${v};`).join(" ")} }`,
        );
      }
    }
}

process.stdout.write(out.join("\n") + "\n");

// Expected resolved values for base (no interaction state) scenes, for the browser check in demo/.
const expected = {};
for (const j of jobs.filter((j) => j.meta.state === null)) {
  const s = scenes.get(j.id);
  const t = node(s, 'track');
  const h = node(s, 'handle');
  expected[j.id.replace(/_base$/, '')] = {
    w: t.w, h: t.h, bg: t.fill, border: t.stroke ?? 'transparent',
    thumbLeft: h.x - t.x, thumbW: h.w, thumbBg: h.fill,
  };
}
writeFileSync(new URL('./demo/public/expected.json', import.meta.url), JSON.stringify(expected));

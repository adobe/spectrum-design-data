function node(type) {
  const n = {
    type,
    name: "",
    x: 0,
    y: 0,
    children: [],
    parent: null,
    width: 40,
    height: 14,
  };
  n.appendChild = (c) => {
    c.parent = n;
    n.children.push(c);
  };
  n.resize = (w, h) => {
    n.width = w;
    n.height = h;
  };
  n.remove = () => {
    if (n.parent) n.parent.children.splice(n.parent.children.indexOf(n), 1);
  };
  n.insertChild = (i, c) => {
    c.parent = n;
    n.children.splice(i, 0, c);
  };
  n.findAll = (pred) =>
    n.children.flatMap((c) => [...(pred(c) ? [c] : []), ...c.findAll(pred)]);
  n.findOne = (pred) => n.findAll(pred)[0] ?? null;
  return n;
}

function fakeFigma(rejectFamily) {
  const loaded = [];
  const page = node("PAGE");
  const messages = [];
  const figma = {
    currentPage: page,
    showUI() {},
    ui: { onmessage: null, postMessage: (m) => messages.push(m) },
    loadFontAsync: async (font) => {
      if (rejectFamily === font.family) throw new Error("font not available");
      loaded.push(font.family + " " + font.style);
    },
    createFrame: () => node("FRAME"),
    createRectangle: () => node("RECTANGLE"),
    createEllipse: () => node("ELLIPSE"),
    createText() {
      const t = node("TEXT");
      let chars = "";
      Object.defineProperty(t, "characters", {
        get: () => chars,
        set: (v) => {
          chars = v;
          t.width = v.length * 6;
        },
      });
      return t;
    },
  };
  return { figma, page, messages, loaded };
}

function mock(rejectFamily) {
  const m = fakeFigma(rejectFamily);
  vm.runInNewContext(code, { figma: m.figma, __html__: "" });
  return m;
}

const count = (n, pred) =>
  (pred(n) ? 1 : 0) + n.children.reduce((s, c) => s + count(c, pred), 0);

test("renders the Layout and Color pages with a block per spec block", async (t) => {
  const { figma, page, messages } = mock();
  await figma.ui.onmessage({
    type: "render-sheet",
    sheet,
    changelog,
    pages: ["Layout", "Color"],
  });
  const done = messages.find((m) => m.type === "render-complete");
  t.truthy(done, JSON.stringify(messages));
  const expected = sheet.pages
    .filter((p) => ["Layout", "Color"].includes(p.title))
    .reduce((s, p) => s + p.blocks.length, 0);
  t.is(done.result.blocksRendered, expected);
  const root = page.children[0];
  t.is(root.name, "Action button – spec (generated)");
  t.is(
    count(root, (n) => n.name?.startsWith("Block – ")),
    expected,
  );
  t.true(count(root, (n) => n.name === "Changelog item") > 0);
});

test("changelog rows list entries, not metadata summaries, and show the PR title", async (t) => {
  const { figma, page } = mock();
  await figma.ui.onmessage({
    type: "render-sheet",
    sheet,
    changelog,
    pages: ["Layout"],
  });
  const rows = [];
  const walk = (n) => {
    if (n.name === "Changelog item") rows.push(n.children[0].characters);
    n.children.forEach(walk);
  };
  walk(page.children[0]);
  const commits = changelog.releases.flatMap((r) => r.commits);
  const withChanges = commits.filter((c) => c.entries.length);
  t.is(rows.length, withChanges.length);
  t.true(rows.every((r) => !/metadata/.test(r)));
  t.true(commits.some((c) => c.metadata));
  t.true(commits.every((c) => c.entries.every((e) => e.class !== "metadata")));
  const pr = commits.find((c) => c.source.type === "pr" && c.entries.length);
  t.true(rows.some((r) => r.includes(pr.source.title)));
});


/**
 * code.js only runs in the Figma plugin sandbox, so this runs it in a vm against a fake
 * `figma` global and sheets generated by `design-data spec-sheet` plus the committed action-button changelog. It checks the
 * structure the plugin builds and that a second render replaces the first.
 */
import test from "ava";
import vm from "node:vm";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const code = readFileSync(join(here, "../code.js"), "utf-8");
const cli =
  process.env.DESIGN_DATA_CLI ??
  join(
    resolve(root, process.env.CARGO_TARGET_DIR ?? "sdk/target"),
    "debug/design-data",
  );
// Sheets are generated, not committed: one `spec-sheet --all` run (the sdk:build dependency of the
// moon task builds the CLI), then each test reads the sheet it needs.
const out = mkdtempSync(join(tmpdir(), "spec-sheets-"));
execFileSync(
  cli,
  [
    "spec-sheet",
    "--all",
    "--changelog-dir",
    join(root, "packages/design-data/changelog"),
    "-o",
    out,
  ],
  { cwd: root, stdio: "pipe" },
);
const generate = (component) =>
  JSON.parse(readFileSync(join(out, `${component}.json`), "utf-8"));
const sheet = generate("action-button");
const changelog = JSON.parse(
  readFileSync(
    join(root, "packages/design-data/changelog/action-button.json"),
    "utf-8",
  ),
);

function node(type) {
  const n = { type, children: [], parent: null, width: 40, height: 14 };
  n.appendChild = (c) => {
    c.parent = n;
    n.children.push(c);
  };
  n.resize = (w, h) => {
    n.width = w;
    n.height = h;
  };
  n.remove = () => {
    if (n.parent) n.parent.children.splice(n.parent.children.indexOf(n), 1);
  };
  n.findOne = (pred) => n.children.find(pred) ?? null;
  return n;
}

function mock(rejectFamily) {
  const loaded = [];
  const page = node("PAGE");
  const messages = [];
  const figma = {
    currentPage: page,
    showUI() {},
    ui: { onmessage: null, postMessage: (m) => messages.push(m) },
    loadFontAsync: async (font) => {
      if (rejectFamily === font.family) throw new Error("font not available");
      loaded.push(font.family + " " + font.style);
    },
    createFrame: () => node("FRAME"),
    createRectangle: () => node("RECTANGLE"),
    createEllipse: () => node("ELLIPSE"),
    createText() {
      const t = node("TEXT");
      let chars = "";
      Object.defineProperty(t, "characters", {
        get: () => chars,
        set: (v) => {
          chars = v;
          t.width = v.length * 6;
        },
      });
      return t;
    },
  };
  vm.runInNewContext(code, { figma, __html__: "" });
  return { figma, page, messages, loaded };
}

const count = (n, pred) =>
  (pred(n) ? 1 : 0) + n.children.reduce((s, c) => s + count(c, pred), 0);

test("renders the Layout and Color pages with a block per spec block", async (t) => {
  const { figma, page, messages } = mock();
  await figma.ui.onmessage({
    type: "render-sheet",
    sheet,
    changelog,
    pages: ["Layout", "Color"],
  });
  const done = messages.find((m) => m.type === "render-complete");
  t.truthy(done, JSON.stringify(messages));
  const expected = sheet.pages
    .filter((p) => ["Layout", "Color"].includes(p.title))
    .reduce((s, p) => s + p.blocks.length, 0);
  t.is(done.result.blocksRendered, expected);
  const root = page.children[0];
  t.is(root.name, "Action button – spec (generated)");
  t.is(
    count(root, (n) => n.name?.startsWith("Block – ")),
    expected,
  );
  t.true(count(root, (n) => n.name === "Changelog item") > 0);
});

test("changelog rows list entries, not metadata summaries, and show the PR title", async (t) => {
  const { figma, page } = mock();
  await figma.ui.onmessage({
    type: "render-sheet",
    sheet,
    changelog,
    pages: ["Layout"],
  });
  const rows = [];
  const walk = (n) => {
    if (n.name === "Changelog item") rows.push(n.children[0].characters);
    n.children.forEach(walk);
  };
  walk(page.children[0]);
  const commits = changelog.releases.flatMap((r) => r.commits);
  const withChanges = commits.filter((c) => c.entries.length);
  t.is(rows.length, withChanges.length);
  t.true(rows.every((r) => !/metadata/.test(r)));
  t.true(commits.some((c) => c.metadata));
  t.true(commits.every((c) => c.entries.every((e) => e.class !== "metadata")));
  const pr = commits.find((c) => c.source.type === "pr" && c.entries.length);
  t.true(rows.some((r) => r.includes(pr.source.title)));
});

test("re-rendering replaces the root frame instead of adding another", async (t) => {
  const { figma, page } = mock();
  await figma.ui.onmessage({
    type: "render-sheet",
    sheet,
    changelog,
    pages: ["Layout"],
  });
  const first = count(page, () => true);
  await figma.ui.onmessage({
    type: "render-sheet",
    sheet,
    changelog,
    pages: ["Layout"],
  });
  t.is(page.children.length, 1);
  t.is(
    count(page, () => true),
    first,
  );
});

test("measurements are drawn from the scene and labelled by the sheet", async (t) => {
  const { figma, page } = mock();
  await figma.ui.onmessage({ type: "render-sheet", sheet, pages: ["Layout"] });
  const legends = [];
  const walk = (n) => {
    if (n.type === "TEXT" && / · \d+px$/.test(n.characters))
      legends.push(n.characters);
    n.children.forEach(walk);
  };
  walk(page.children[0]);
  t.true(legends.includes("component-height-100 · 32px"), legends.join("|"));
});

test("a failed render keeps the previous render and drops the half-built one", async (t) => {
  const { figma, page, messages } = mock();
  await figma.ui.onmessage({ type: "render-sheet", sheet, pages: ["Layout"] });
  const before = page.children[0];
  const broken = JSON.parse(JSON.stringify(sheet));
  delete broken.pages[0].blocks[1].render.view;
  await figma.ui.onmessage({
    type: "render-sheet",
    sheet: broken,
    pages: ["Layout"],
  });
  t.truthy(messages.find((m) => m.type === "render-error"));
  t.is(page.children.length, 1);
  t.is(page.children[0], before);
});

test("a table-only sheet renders its token rows and says there is no visual", async (t) => {
  const stubName = JSON.parse(
    readFileSync(join(out, "index.json"), "utf-8"),
  ).components.find((c) => !c.visual && c.blocks > 0).component;
  const stub = generate(stubName);
  t.false(stub.visual);
  const { figma, page, messages } = mock();
  await figma.ui.onmessage({ type: "render-sheet", sheet: stub });
  const done = messages.find((m) => m.type === "render-complete");
  t.truthy(done, JSON.stringify(messages));
  const blocks = stub.pages.reduce((n, p) => n + p.blocks.length, 0);
  t.is(done.result.blocksRendered, blocks);
  const frames = [];
  const walk = (n) => {
    frames.push(n);
    n.children.forEach(walk);
  };
  walk(page.children[0]);
  t.is(
    frames.filter((n) => n.characters === "No visual recipe yet").length,
    blocks,
  );
});

const textNodes = (n) => [
  ...(n.type === "TEXT" ? [n] : []),
  ...n.children.flatMap(textNodes),
];

test("text is set in Adobe Clean Spectrum VF, with the weight from the scene", async (t) => {
  const { figma, page, messages, loaded } = mock();
  await figma.ui.onmessage({ type: "render-sheet", sheet, pages: ["Layout"] });
  t.truthy(messages.find((m) => m.type === "render-complete"));
  t.deepEqual(loaded, [
    "Adobe Clean Spectrum VF Regular",
    "Adobe Clean Spectrum VF Medium",
    "Adobe Clean Spectrum VF Bold",
  ]);
  const texts = textNodes(page.children[0]);
  t.true(texts.length > 0);
  t.true(texts.every((n) => n.fontName.family === "Adobe Clean Spectrum VF"));
  const scene = sheet.pages[0].blocks[0].render.scene;
  const weight = scene.nodes.find((n) => n.part === "label").font_weight;
  const label = texts.find((n) => n.name === "label");
  t.is(label.fontName.style, { bold: "Bold", medium: "Medium" }[weight]);
});


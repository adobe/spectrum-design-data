// Write THIRD-PARTY-NOTICES.txt from an esbuild metafile: one entry per package bundled
// into the output, with its version, license and the license text the package ships.
// Packages that ship no license file and are Apache-2.0 point to the full text appended once.
// Usage: node notices.mjs <metafile> <output-js-key> <notices-file> <apache-2.0-license-file>
import {
  existsSync,
  readdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";

const [metafile, outKey, notices, apacheFile] = process.argv.slice(2);
const inputs = Object.keys(
  JSON.parse(readFileSync(metafile, "utf8")).outputs[outKey].inputs,
);
const roots = new Map();
for (const f of inputs) {
  const i = f.lastIndexOf("node_modules/");
  if (i < 0) continue;
  const parts = f.slice(i + 13).split("/");
  const name = parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0];
  roots.set(name, f.slice(0, i + 13) + name);
}
const entries = [...roots]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, root]) => {
    const dir = dirname(realpathSync(join(root, "package.json")));
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const file = readdirSync(dir).find((n) => /^licen[cs]e(\.\w+)?$/i.test(n));
    const text = file ? readFileSync(join(dir, file), "utf8").trim() : null;
    return `${name}@${pkg.version}\nLicense: ${pkg.license}\n\n${text ?? (pkg.license === "Apache-2.0" ? "Licensed under the Apache License, Version 2.0 (full text at the end of this file)." : `(this package ships no license file; see ${pkg.license} at ${pkg.repository?.url ?? pkg.homepage ?? "its npm page"})`)}`;
  });
const rule = `\n\n${"=".repeat(72)}\n\n`;
writeFileSync(
  notices,
  `Third-party software bundled into spectrum-controls.js.\nGenerated by controls/build.sh; do not edit.\n${rule}${entries.join(rule)}${rule}Apache License, Version 2.0\n\n${readFileSync(apacheFile, "utf8").trim()}\n`,
);
console.log(`${entries.length} packages -> ${notices}`);

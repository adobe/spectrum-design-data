// Generates Copilot and Cursor rule files from .ai/rules and keeps the native
// discovery symlinks for Claude and Cursor pointed at the shared source.
//
//   node .ai/scripts/sync.js            write generated files and symlinks
//   node .ai/scripts/sync.js --check    fail if anything is stale

import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  readlinkSync,
  rmSync,
  symlinkSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { REPO_ROOT, applyOutputs, isMain, parseFrontmatter } from "./lib.js";

export const GENERATED_MARKER = "GENERATED by .ai/scripts/sync.js";

export const SYMLINKS = [
  { link: ".claude/rules", target: "../.ai/rules" },
  { link: ".claude/skills", target: "../.ai/skills" },
  { link: ".cursor/skills", target: "../.ai/skills" },
];

const GENERATED_DIRS = [
  { dir: ".github/instructions", suffix: ".instructions.md" },
  { dir: ".cursor/rules", suffix: ".mdc" },
];

export function readRules(root = REPO_ROOT) {
  const dir = join(root, ".ai/rules");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((file) => {
      const text = readFileSync(join(dir, file), "utf8");
      const { data, body } = parseFrontmatter(text);
      return { name: file.replace(/\.md$/, ""), file, data, body };
    });
}

export function splitGlobs(value) {
  return String(value ?? "")
    .split(",")
    .map((g) => g.trim())
    .filter(Boolean);
}

function banner(name) {
  return `<!-- ${GENERATED_MARKER} from .ai/rules/${name}.md. Do not edit; edit the source and run \`pnpm ai:sync\`. -->`;
}

export function renderCopilot(rule) {
  const globs = splitGlobs(rule.data.globs).join(",");
  return `---\napplyTo: "${globs}"\ndescription: "${rule.data.description}"\n---\n${banner(rule.name)}\n\n${rule.body.replace(/^\n+/, "")}`;
}

export function renderCursor(rule) {
  const globs = splitGlobs(rule.data.globs).join(",");
  return `---\ndescription: ${rule.data.description}\nglobs: ${globs}\nalwaysApply: false\n---\n${banner(rule.name)}\n\n${rule.body.replace(/^\n+/, "")}`;
}

export function expectedOutputs(root = REPO_ROOT) {
  const outputs = new Map();
  for (const rule of readRules(root)) {
    if (!rule.data) continue;
    outputs.set(
      `.github/instructions/${rule.name}.instructions.md`,
      renderCopilot(rule),
    );
    outputs.set(`.cursor/rules/${rule.name}.mdc`, renderCursor(rule));
  }
  return outputs;
}

/** Generated files on disk that no longer have a source rule. */
export function orphanedOutputs(outputs, root = REPO_ROOT) {
  const orphans = [];
  for (const { dir, suffix } of GENERATED_DIRS) {
    const abs = join(root, dir);
    if (!existsSync(abs)) continue;
    for (const file of readdirSync(abs)) {
      const rel = `${dir}/${file}`;
      if (!file.endsWith(suffix) || outputs.has(rel)) continue;
      if (readFileSync(join(abs, file), "utf8").includes(GENERATED_MARKER)) {
        orphans.push(rel);
      }
    }
  }
  return orphans;
}

export function symlinkProblems(root = REPO_ROOT) {
  const problems = [];
  for (const { link, target } of SYMLINKS) {
    const abs = join(root, link);
    let stat = null;
    try {
      stat = lstatSync(abs);
    } catch {
      problems.push({ link, target, reason: "missing" });
      continue;
    }
    if (!stat.isSymbolicLink()) {
      problems.push({ link, target, reason: "not a symlink" });
    } else if (readlinkSync(abs) !== target) {
      problems.push({
        link,
        target,
        reason: `points to ${readlinkSync(abs)}`,
      });
    }
  }
  return problems;
}

export function sync({ check = false, root = REPO_ROOT } = {}) {
  const outputs = expectedOutputs(root);
  const stale = applyOutputs(outputs, { check });
  const orphans = orphanedOutputs(outputs, root);
  const links = symlinkProblems(root);

  if (!check) {
    for (const rel of orphans) rmSync(join(root, rel));
    for (const { link, target, reason } of links) {
      if (reason === "not a symlink") continue;
      const abs = join(root, link);
      mkdirSync(dirname(abs), { recursive: true });
      rmSync(abs, { force: true });
      symlinkSync(target, abs);
    }
  }

  const problems = [
    ...stale.map((p) => `out of date: ${p}`),
    ...orphans.map((p) => `orphaned generated file: ${p}`),
    ...links.map((l) => `symlink ${l.link} -> ${l.target}: ${l.reason}`),
  ];
  return check ? problems : problems.filter((p) => p.includes("not a symlink"));
}

if (isMain(import.meta.url)) {
  const check = process.argv.includes("--check");
  const problems = sync({ check });
  if (problems.length > 0) {
    console.error(problems.map((p) => `  ${p}`).join("\n"));
    console.error(
      check ? "AI resources are stale. Run `pnpm ai:sync`." : "Sync failed.",
    );
    process.exit(1);
  }
  console.log(check ? "AI resources are up to date." : "AI resources synced.");
}

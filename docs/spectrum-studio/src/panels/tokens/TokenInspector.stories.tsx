import { useState } from "react";
import { ActionButton } from "@react-spectrum/s2";
import type { Meta, StoryObj } from "@storybook/react";
import { expect, fn, userEvent, waitFor, within } from "@storybook/test";
import { TokenInspector, type TokenInspectorProps } from "./TokenInspector";
import {
  inspectorModeKey,
  inspectorModeSets,
  inspectorRows,
  inspectorTaxonomy,
} from "../../../tests/fixtures/token-inspector";
import { DEFAULT_COLOR_OUTPUT } from "../../features/color-system/outputSettings";
import { commitDialogDraft } from "../../features/tokens/dialogModel";
import { createColorDefaults } from "../../data/defaults";

function ControlledInspector(args: TokenInspectorProps) {
  const [open, setOpen] = useState(true);
  const [edits, setEdits] = useState(args.edits);
  const rows = inspectorRows(edits);
  const token = rows.find(
    (row) => row.token.id === args.token.id && row.context === inspectorModeKey,
  )!.token;
  return (
    <>
      <ActionButton onPress={() => setOpen(true)}>Open token</ActionButton>
      {open && (
        <TokenInspector
          {...args}
          token={token}
          rows={rows}
          edits={edits}
          onSave={(draft) => {
            setEdits(commitDialogDraft(draft, rows, edits, args.taxonomy));
            args.onSave(draft);
          }}
          onClose={() => {
            setOpen(false);
            args.onClose();
          }}
        />
      )}
    </>
  );
}
const rows = inspectorRows();
const meta = {
  title: "Panels/Token inspector",
  component: TokenInspector,
  render: (args) => <ControlledInspector {...args} />,
  args: {
    token: rows[0].token,
    rows,
    edits: {},
    taxonomy: inspectorTaxonomy,
    modeSets: inspectorModeSets,
    modeKey: inspectorModeKey,
    isEditing: false,
    releasedIds: new Set(["primary", "replacement", "spacing", "shadow"]),
    settings: DEFAULT_COLOR_OUTPUT,
    colorSystem: createColorDefaults(),
    aliases: [],
    components: [{ id: "button", label: "Button", count: 4 }],
    onSave: fn(),
    onClose: fn(),
    onOpenToken: fn(),
    onOpenComponent: fn(),
  },
} satisfies Meta<typeof TokenInspector>;
export default meta;
type Story = StoryObj<typeof meta>;

export const ReadOnly: Story = {
  args: {
    modeSets: inspectorModeSets.map((set) =>
      set.id === "contrast"
        ? {
            ...set,
            modes: set.modes
              .filter((mode) => mode.id !== "low")
              .map((mode) => ({ ...mode, iconId: "contrast" as const })),
          }
        : set,
    ),
  },
  play: async ({ canvasElement }) => {
    const body = within(canvasElement.ownerDocument.body);
    await waitFor(() => expect(body.getByRole("dialog")).toBeVisible());
    await expect(
      body.queryByRole("combobox", { name: "Mode value" }),
    ).not.toBeInTheDocument();
    await expect(
      body.queryByRole("textbox", { name: "Description" }),
    ).not.toBeInTheDocument();
    await expect(body.getByText("Released", { exact: true })).toBeVisible();
    const contrast = within(body.getByRole("radiogroup", { name: "Contrast" }));
    await expect(
      contrast.getByRole("radio", { name: "Regular" }),
    ).toHaveTextContent("Regular");
    await expect(
      contrast.getByRole("radio", { name: "High" }),
    ).toHaveTextContent("High");
    await userEvent.click(contrast.getByRole("radio", { name: "High" }));
    await expect(contrast.getByRole("radio", { name: "High" })).toBeChecked();
    await userEvent.click(body.getByRole("radio", { name: "Dark" }));
    await expect(body.getByText("#7abaff", { exact: true })).toBeVisible();
    canvasElement.dataset.playComplete = "true";
  },
};
export const Editing: Story = {
  args: { isEditing: true },
  play: async ({ canvasElement }) => {
    const body = within(canvasElement.ownerDocument.body);
    await waitFor(() =>
      expect(body.getByRole("combobox", { name: "Mode value" })).toBeVisible(),
    );
    await waitFor(() =>
      expect(body.getByText("Value generated by formula")).toBeVisible(),
    );
    await expect(
      body.getByRole("textbox", { name: "Description" }),
    ).toBeVisible();
    await userEvent.click(
      within(body.getByRole("grid", { name: "Classification" })).getByText(
        "action-background",
        { exact: true },
      ),
    );
    const termField = body.getByRole("combobox", { name: "Change Token" });
    await userEvent.click(termField);
    await userEvent.keyboard("{ArrowDown}");
    await expect(
      await body.findByRole("option", {
        name: "replacement-background",
      }),
    ).toBeVisible();
    await expect(
      body.queryByRole("option", {
        name: "Token: replacement-background",
      }),
    ).not.toBeInTheDocument();
    await userEvent.keyboard("{Escape}");
    canvasElement.dataset.playComplete = "true";
  },
};

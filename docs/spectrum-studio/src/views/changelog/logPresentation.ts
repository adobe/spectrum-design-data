import type { ChangeField, ChangeItem } from "../../features/changelog/changes";

export function generatedSourceDescription(item: ChangeItem): string {
  if (item.upstream?.length)
    return `Generated from ${item.upstream.map((source) => source.title).join(", ")}`;
  return item.sourceKind === "semantic-token"
    ? "Generated by Structure and rule evaluation"
    : item.sourceKind === "token"
      ? "Generated by its foundation and mode configuration"
      : `Generated by ${item.title}`;
}

export function changeBadgeLabel(kind: ChangeItem["kind"]): string {
  return kind === "new"
    ? "New"
    : kind === "removed"
      ? "Removed"
      : kind === "deprecated"
        ? "Deprecated"
        : "Modified";
}

export function fieldResetDisabledReason(
  field: ChangeField,
  editing: boolean,
): string | undefined {
  if (!editing) return "Enter edit mode to reset this field.";
  if (!field.address && !field.generated)
    return "This field has no registered independent reset address. Reset its card or edit its source.";
}

export function groupChangedFields(
  fields: readonly ChangeField[],
): Map<string, ChangeField[]> {
  const groups = new Map<string, ChangeField[]>();
  for (const field of fields) {
    const group = groups.get(field.key) ?? [];
    group.push(field);
    groups.set(field.key, group);
  }
  return groups;
}

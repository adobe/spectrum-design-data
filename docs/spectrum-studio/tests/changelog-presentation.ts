import assert from "node:assert/strict";
import {
  changeBadgeLabel,
  fieldResetDisabledReason,
  generatedSourceDescription,
  groupChangedFields,
} from "../src/views/changelog/logPresentation";
import type {
  ChangeField,
  ChangeItem,
} from "../src/features/changelog/changes";

const fields: ChangeField[] = [
  {
    id: "light",
    key: "Value",
    context: { key: "light", label: "Color scheme: Light" },
    before: "8px",
    after: "12px",
    generated: true,
  },
  {
    id: "dark",
    key: "Value",
    context: { key: "dark", label: "Color scheme: Dark" },
    before: "8px",
    after: "16px",
    generated: true,
  },
  {
    id: "reference",
    key: "Reference",
    context: { key: "dark", label: "Color scheme: Dark" },
    before: "a",
    after: "b",
    generated: true,
  },
];
const groups = groupChangedFields(fields);
assert.deepEqual([...groups.keys()], ["Value", "Reference"]);
assert.equal(
  groups.get("Value")!.length,
  2,
  "all changed contexts are nested below one concise parent",
);
assert.equal(
  [...groups.values()].flat().length,
  fields.length,
  "headings do not introduce changed rows or duplicate counts",
);
assert.deepEqual([...groups.values()].flat(), fields);
const item: ChangeItem = {
  id: "token",
  topic: "tokens",
  sourceKind: "semantic-token",
  title: "Token",
  kind: "modified",
  fields,
};
assert.equal(
  generatedSourceDescription(item),
  "Generated by Structure and rule evaluation",
);
item.upstream = [
  { title: "Global / Base", address: { path: ["spacing"], expected: {} } },
];
assert.equal(generatedSourceDescription(item), "Generated from Global / Base");
assert.match(fieldResetDisabledReason(fields[0], false)!, /edit mode/);
assert.equal(
  fieldResetDisabledReason(fields[0], true),
  undefined,
  "generated fields open explained choices even if independent override is unsupported",
);
assert.match(
  fieldResetDisabledReason({ key: "Status" }, true)!,
  /no registered independent reset/,
);
for (const [kind, label] of [
  ["new", "New"],
  ["removed", "Removed"],
  ["deprecated", "Deprecated"],
  ["modified", "Modified"],
] as const) {
  assert.equal(changeBadgeLabel(kind), label);
}
console.log(
  "Changes presentation: nested mode rows, exact row counting, generated provenance, reset reasons and kind badges passed.",
);

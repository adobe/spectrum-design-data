import assert from "node:assert/strict";
import {
  compareDesignData,
  type AnalysisInput,
  type AnalysisRecord,
} from "../src/features/design-data/comparison";
import {
  buildIdentityReport,
  identityReportSummary,
  isIdentityReportCurrent,
} from "../src/features/design-data/identityReport";
import { reviewedColorMappings } from "../src/features/design-data/mappings";
import { assessPalette } from "../src/features/design-data/paletteAssessment";
import {
  comparisonName,
  idStatus,
  matchedBy,
} from "../src/features/design-data/tokenPairing";

const input = (
  kind: "working" | "reference",
  records: AnalysisRecord[],
): AnalysisInput => ({
  source: {
    kind,
    hash: "fixture",
    root: "fixture",
    revision: "fixture",
    version: "fixture",
    dirty: false,
    validator: "fixture",
  },
  records,
  inventoryStatus: "complete",
  categories: [...new Set(records.map((row) => row.category))],
  schemas: [],
  errors: [],
  limitations: [],
});
const row = (
  id: string,
  extra: Partial<AnalysisRecord> = {},
): AnalysisRecord => ({
  id,
  name: id,
  category: "tokens",
  classification: "generated",
  source: "fixture",
  pointer: `/${id}`,
  ...extra,
});
const colorScheme = row("color-scheme", {
  category: "mode-sets",
  identity: "color-scheme",
  value: { name: "colorScheme", modes: ["light", "dark"], default: "light" },
});
const registry = row("registry-blue", {
  category: "registry",
  value: { id: "blue", label: "Blue" },
});

// The shared name key runs app names through the crosswalk and leaves
// design-data names alone. Mode axes and legacy keys never decide a pair.
const vocabulary = [registry];
assert.deepEqual(
  comparisonName(
    row("app", {
      tokenType: "colors",
      structuredName: {
        colorFamily: "Blue",
        scaleIndex: "100",
        renderingBehavior: "opaque",
        colorScheme: "dark",
        legacyKey: "blue-100",
      },
    }),
    "app",
    vocabulary,
    ["colorScheme"],
  ),
  { property: "color", colorFamily: "blue", scaleIndex: 100 },
);
assert.deepEqual(
  comparisonName(
    row("reference", {
      structuredName: { colorFamily: "blue", scaleIndex: "100" },
    }),
    "reference",
    vocabulary,
    [],
  ),
  { colorFamily: "blue", scaleIndex: "100" },
  "Design-data names are not translated.",
);

// Blue keeps design-data's row UUID and concept, so it pairs by ID. Accent
// is generated by Studio with its own IDs, so it can only pair by name.
const blue = (scheme: string, value: string, extra = {}) =>
  row(`blue-100-${scheme}`, {
    identity: `blue-100-${scheme}`,
    conceptId: "blue-100",
    context: { colorScheme: scheme },
    value,
    ...extra,
  });
const appBlue = (scheme: string, value: string) =>
  blue(scheme, value, {
    tokenType: "colors",
    structuredName: { colorFamily: "blue", scaleIndex: "100" },
  });
const referenceBlue = (scheme: string, value: string) =>
  blue(scheme, value, {
    classification: "authored",
    structuredName: { property: "color", colorFamily: "blue", scaleIndex: 100 },
  });
const accent = row("studio-accent-100-light", {
  identity: "studio-accent-100-light",
  conceptId: "studio-accent-100",
  tokenType: "colors",
  context: { colorScheme: "light" },
  structuredName: {
    colorRole: "accent",
    scaleIndex: "100",
    renderingBehavior: "opaque",
  },
  value: "#e0f2ff",
});
const app = input("working", [
  colorScheme,
  appBlue("light", "#e0f2ff"),
  appBlue("dark", "#0a2a4a"),
  accent,
]);
const referenceAccent = row("design-data-accent-100", {
  identity: "design-data-accent-100",
  conceptId: "design-data-accent-100-concept",
  classification: "authored",
  structuredName: { property: "color", scaleIndex: 100, colorRole: "accent" },
  context: { colorScheme: "light" },
  value: "#e0f2ff",
});
const reference = input("reference", [
  colorScheme,
  registry,
  referenceBlue("light", "#e0f2ff"),
  referenceBlue("dark", "#0a2a4a"),
  referenceAccent,
]);

const report = compareDesignData(app, reference, []);
const finding = (appId: string) =>
  report.findings.find(
    (item) => item.app?.id === appId && item.reference !== undefined,
  );
assert.equal(finding("blue-100-light")?.confidence, "exact-identity");
assert.equal(
  finding("studio-accent-100-light")?.reference?.id,
  referenceAccent.id,
);
assert.equal(
  finding("studio-accent-100-light")?.confidence,
  "canonical-key",
  "A Studio token with its own IDs pairs by its crosswalked name.",
);
assert(
  !report.findings.some(
    (item) =>
      item.app?.id === accent.id &&
      ["field-gap", "app-only", "ambiguous"].includes(item.classification),
  ),
  "Crosswalk-only fields do not raise field gaps on a name pair.",
);

const entry = (side: "app" | "reference", id: string) =>
  report.colorOpacity!.inventory!.entries.find(
    (item) => item.side === side && item.record.id === id,
  )!;
assert.equal(entry("app", "blue-100-light").presence, "matched");
assert.equal(entry("app", "blue-100-light").matchedBy, "id");
assert.equal(entry("app", "blue-100-light").idStatus, "same");
assert.equal(entry("app", accent.id).presence, "matched");
assert.equal(entry("app", accent.id).matchedBy, "name");
assert.equal(entry("app", accent.id).idStatus, "differs");
assert.equal(entry("reference", referenceAccent.id).matchedBy, "name");

// Names are the last resort: a reference token already claimed by a Studio
// token's UUID or concept is never offered to a different token by name.
const lookalike = row("studio-blue-lookalike", {
  identity: "studio-blue-lookalike",
  tokenType: "colors",
  context: { colorScheme: "light" },
  structuredName: { colorFamily: "blue", scaleIndex: "100" },
  value: "#e0f2ff",
});
const claimed = compareDesignData(
  input("working", [...app.records, lookalike]),
  reference,
  [],
);
assert.equal(
  claimed.findings.find((item) => item.app?.id === "blue-100-light")?.reference
    ?.id,
  "blue-100-light",
  "An exact ID pair is not turned into an ambiguous one.",
);
assert(
  !claimed.findings.some(
    (item) => item.app?.id === lookalike.id && item.reference !== undefined,
  ),
);

// Design-data's accent is one alias row for every mode, while Studio has one
// row per mode.
{
  const aliasAccent = {
    ...referenceAccent,
    context: undefined,
    value: undefined,
    reference: "blue-100-light",
  };
  const darkAccent = {
    ...accent,
    id: "studio-accent-100-dark",
    identity: "studio-accent-100-dark",
    context: { colorScheme: "dark" },
    value: "#0a2a4a",
  };
  const probe = compareDesignData(
    input("working", [...app.records, darkAccent]),
    input("reference", [
      ...reference.records.filter((item) => item.id !== referenceAccent.id),
      aliasAccent,
    ]),
    [],
  );
  const entries = probe.colorOpacity!.inventory!.entries;
  const entry = (side: string, id: string) =>
    entries.find((item) => item.side === side && item.record.id === id)!;
  // A mode-independent design-data alias pairs with each per-mode Studio row
  // and counts as one match, not an ambiguous one.
  assert.equal(entry("reference", aliasAccent.id).presence, "matched");
  assert.deepEqual(entry("reference", aliasAccent.id).counterparts, [
    darkAccent.id,
    accent.id,
  ]);
  assert.equal(entry("reference", aliasAccent.id).matchedBy, "name");
  for (const id of [accent.id, darkAccent.id]) {
    assert.equal(entry("app", id).presence, "matched");
    assert.equal(entry("app", id).matchedBy, "name");
  }
  // Neither Studio row has its own design-data row to adopt.
  const identities = buildIdentityReport(
    probe.colorOpacity!.inventory!,
    app,
    reference,
  );
  for (const id of [accent.id, darkAccent.id])
    assert.equal(
      identities.items.find((item) => item.appId === id)?.group,
      "missing-mode",
    );
}
// Two Studio tokens with the same name in the same mode stay ambiguous; the
// mode fan-out rule does not hide a real collision.
{
  const copy = {
    ...accent,
    id: "studio-accent-copy-100-light",
    identity: "studio-accent-copy-100-light",
    conceptId: "studio-accent-copy-100",
  };
  const inventory = compareDesignData(
    input("working", [...app.records, copy]),
    reference,
    [],
  ).colorOpacity!.inventory!;
  const shared = inventory.entries.find(
    (item) =>
      item.side === "reference" && item.record.id === referenceAccent.id,
  )!;
  assert.notEqual(shared.presence, "matched");
}

// The identity report groups each Studio token by the design-data IDs it
// could adopt, and is only valid for the inputs it was built from.
{
  const darkAccent = {
    ...accent,
    id: "studio-accent-100-dark",
    identity: "studio-accent-100-dark",
    context: { colorScheme: "dark" },
    value: "#0a2a4a",
  };
  const fresh = row("studio-new-token", {
    identity: "studio-new-token",
    tokenType: "colors",
    context: { colorScheme: "light" },
    structuredName: { colorRole: "brand-new", scaleIndex: "100" },
    value: "#123456",
  });
  const working = input("working", [...app.records, darkAccent, fresh]);
  const identities = buildIdentityReport(
    compareDesignData(working, reference, []).colorOpacity!.inventory!,
    working,
    reference,
  );
  const group = (id: string) =>
    identities.items.find((item) => item.appId === id);
  assert.equal(group("blue-100-light")?.group, "same-id");
  assert.equal(group(accent.id)?.group, "one-candidate");
  assert.deepEqual(group(accent.id)?.targets, [
    {
      referenceId: referenceAccent.id,
      conceptId: referenceAccent.conceptId,
      uuid: referenceAccent.identity,
    },
  ]);
  assert.equal(group(darkAccent.id)?.group, "missing-mode");
  assert.deepEqual(group(darkAccent.id)?.targets, [
    { conceptId: referenceAccent.conceptId },
  ]);
  assert.equal(group(fresh.id)?.group, "new");
  assert.equal(identities.complete, true);
  assert.equal(identities.counts.color?.["same-id"], 2);
  assert.equal(identities.counts.color?.["one-candidate"], 1);
  assert(isIdentityReportCurrent(identities, working, reference));
  assert(
    !isIdentityReportCurrent(identities, working, {
      ...reference,
      source: { ...reference.source, hash: "changed" },
    }),
    "A report built from other inputs is stale.",
  );
  assert.match(
    identityReportSummary(identities).join("\n"),
    /color: 2 \/ 1 \/ 0 \/ 1 \/ 1/,
  );
}

// Provenance helpers agree with the pairing order.
assert.equal(matchedBy(appBlue("light", ""), referenceBlue("light", "")), "id");
assert.equal(
  matchedBy(
    { ...appBlue("light", ""), identity: "other" },
    referenceBlue("light", ""),
  ),
  "concept",
);
assert.equal(matchedBy(accent, referenceAccent, true), "reviewed");
assert.equal(matchedBy(accent, referenceAccent), "name");
assert.equal(idStatus(accent, referenceAccent), "differs");

// Reviewed color-ramp pairs read the crosswalk's names, so legacy
// colorName/contrastValue keys and current colorFamily/scaleIndex keys pair
// the same way. Families come from design-data's palette, not a local list.
const palette = (family: string, scheme = "light") =>
  row(`palette-${family}-100-${scheme}`, {
    classification: "authored",
    source: "tokens/color-palette.tokens.json",
    structuredName: { property: "color", colorFamily: family, scaleIndex: 100 },
    context: { colorScheme: scheme, contrast: "regular" },
  });
const ramp = (
  id: string,
  structuredName: Record<string, unknown>,
  extra: Partial<AnalysisRecord> = {},
) =>
  row(id, {
    structuredName,
    context: { colorScheme: "light", contrast: "regular" },
    ...extra,
  });
const rampReference = input("reference", [
  registry,
  row("registry-seafoam", {
    category: "registry",
    value: { id: "seafoam", label: "Seafoam" },
  }),
  palette("blue"),
  palette("seafoam"),
  palette("seafoam", "dark"),
]);
const rampPairs = reviewedColorMappings(
  input("working", [
    ramp("legacy-blue", {
      property: "color",
      colorName: "blue",
      contrastValue: "100",
    }),
    ramp(
      "current-seafoam",
      {
        property: "color",
        colorFamily: "Seafoam",
        scaleIndex: "100",
        renderingBehavior: "opaque",
      },
      { tokenType: "colors" },
    ),
  ]),
  rampReference,
);
assert.deepEqual(
  rampPairs.map((pair) => [pair.app, pair.reference]),
  [
    ["legacy-blue", "palette-blue-100-light"],
    ["current-seafoam", "palette-seafoam-100-light"],
  ],
);
assert.deepEqual(
  rampPairs[0].nameFields,
  {
    colorName: { reference: "colorFamily" },
    contrastValue: { reference: "scaleIndex", normalization: "integer" },
  },
  "Legacy keys get the crosswalk's renames, the same pair the old hard-coded mapping declared.",
);
assert.deepEqual(rampPairs[1].nameFields, {
  colorFamily: { reference: "colorFamily" },
  scaleIndex: { reference: "scaleIndex", normalization: "integer" },
});

// Palette review called on its own uses the same shared pairs (no second
// label matcher), so the "Seafoam" label row is paired with the shared rationale.
{
  const modes = [
    row("scheme", {
      category: "mode-sets",
      value: {
        name: "colorScheme",
        modes: ["light", "dark"],
        default: "light",
      },
    }),
    row("contrast", {
      category: "mode-sets",
      value: { name: "contrast", modes: ["regular"], default: "regular" },
    }),
  ];
  const seafoam = row("registry-seafoam", {
    category: "registry",
    vocabulary: "color-family",
    value: { id: "seafoam", label: "Seafoam" },
  });
  const assessment = assessPalette(
    input("working", [
      ...modes,
      ramp(
        "current-seafoam",
        { property: "color", colorFamily: "Seafoam", scaleIndex: "100" },
        { tokenType: "colors" },
      ),
    ]),
    input("reference", [...modes, seafoam, palette("seafoam")]),
    [],
    [],
  );
  const paired = assessment.concepts
    .flatMap((concept) => concept.rows)
    .find((item) => item.app?.id === "current-seafoam");
  assert.equal(paired?.reference.id, "palette-seafoam-100-light");
  assert.match(paired?.mapping?.rationale ?? "", /^foundation-color-ramp-v2/);
}
assert.equal(
  reviewedColorMappings(
    input("working", [
      ramp(
        "studio-accent",
        { property: "color", colorFamily: "accent", scaleIndex: 100 },
        { tokenType: "colors" },
      ),
    ]),
    rampReference,
  ).length,
  0,
  "A family design-data's palette does not publish is not paired.",
);


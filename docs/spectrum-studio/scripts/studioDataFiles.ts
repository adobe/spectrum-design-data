import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  STUDIO_DATA_ENTRY,
  composeStudioData,
  serializeStudioDataFile,
  splitStudioData,
} from "../src/data/studioData";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const studioDataDirectory = resolve(appRoot, "data/studio");
export const studioDataIndex = resolve(
  appRoot,
  "src/data/studioData.generated.ts",
);

function jsonFiles(directory: string): string[] {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true, recursive: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) =>
      relative(directory, join(entry.parentPath, entry.name))
        .split("\\")
        .join("/"),
    )
    .sort();
}

export function readStudioDataFiles(
  directory = studioDataDirectory,
): Record<string, unknown> {
  return Object.fromEntries(
    jsonFiles(directory).map((file) => [
      file,
      JSON.parse(readFileSync(join(directory, file), "utf8")),
    ]),
  );
}

/** The composed dataset as stored on disk, before Studio's load-time upgrades. */
export function readStudioDataset(directory = studioDataDirectory): unknown {
  return composeStudioData(readStudioDataFiles(directory));
}

/** TypeScript that imports every file and keeps each file's inferred JSON type. */
export function studioDataIndexSource(files: ReadonlyMap<string, unknown>) {
  const names = [...files.keys()].sort((left, right) =>
    left === STUDIO_DATA_ENTRY
      ? -1
      : right === STUDIO_DATA_ENTRY
        ? 1
        : left.localeCompare(right, "en"),
  );
  const variable = new Map(names.map((file, index) => [file, `file${index}`]));
  interface Node {
    children: Map<string, Node | string>;
  }
  const tree: Node = { children: new Map() };
  const entry = files.get(STUDIO_DATA_ENTRY);
  const visit = (value: unknown, node: Node) => {
    if (!value || typeof value !== "object" || Array.isArray(value)) return;
    for (const [key, child] of Object.entries(value)) {
      if (
        child &&
        typeof child === "object" &&
        !Array.isArray(child) &&
        typeof (child as { $file?: unknown }).$file === "string"
      )
        node.children.set(
          key,
          variable.get((child as { $file: string }).$file)!,
        );
      else {
        const next: Node = { children: new Map() };
        visit(child, next);
        if (next.children.size) node.children.set(key, next);
      }
    }
  };
  visit(entry, tree);
  const type = (base: string, node: Node, indent: string): string => {
    const keys = [...node.children.keys()];
    const fields = keys.map((key) => {
      const child = node.children.get(key)!;
      const value =
        typeof child === "string"
          ? `typeof ${child}`
          : type(`${base}[${JSON.stringify(key)}]`, child, `${indent}  `);
      return `${indent}  ${JSON.stringify(key)}: ${value};`;
    });
    return `Omit<${base}, ${keys.map((key) => JSON.stringify(key)).join(" | ")}> & {\n${fields.join("\n")}\n${indent}}`;
  };
  return [
    "// Copyright 2026 Adobe. All rights reserved.",
    "// Generated by scripts/studio-data.ts from data/studio/. Do not edit.",
    'import { composeStudioData } from "./studioData";',
    ...names.map(
      (file) =>
        `import ${variable.get(file)} from "../../data/studio/${file}" with { type: "json" };`,
    ),
    "",
    `type Entry = typeof ${variable.get(STUDIO_DATA_ENTRY)};`,
    "",
    "/** The stored dataset, typed as if it were still one JSON file. */",
    `export type StudioDataset = ${type("Entry", tree, "")};`,
    "",
    "export const studioDataFiles = {",
    ...names.map((file) => `  ${JSON.stringify(file)}: ${variable.get(file)},`),
    "};",
    "",
    "export const studioDataset = composeStudioData(",
    "  studioDataFiles,",
    ") as StudioDataset;",
    "",
  ].join("\n");
}

/** Every file the dataset should produce, keyed by absolute path. */
export function studioDataOutputs(dataset: unknown): Map<string, string> {
  const files = splitStudioData(dataset);
  const outputs = new Map(
    [...files].map(([file, value]) => [
      join(studioDataDirectory, file),
      serializeStudioDataFile(value),
    ]),
  );
  outputs.set(studioDataIndex, studioDataIndexSource(files));
  return outputs;
}

/** Files that differ from the dataset, plus stored files it no longer uses. */
export function staleStudioData(dataset: unknown): string[] {
  const outputs = studioDataOutputs(dataset);
  const stale = [...outputs]
    .filter(
      ([path, text]) =>
        !existsSync(path) || readFileSync(path, "utf8") !== text,
    )
    .map(([path]) => path);
  for (const file of jsonFiles(studioDataDirectory)) {
    const path = join(studioDataDirectory, file);
    if (!outputs.has(path)) stale.push(path);
  }
  return stale.map((path) => relative(appRoot, path));
}

/** Writes only the files that changed and removes files no longer used. */
export function writeStudioData(dataset: unknown): string[] {
  const outputs = studioDataOutputs(dataset);
  const changed = staleStudioData(dataset);
  for (const file of changed) {
    const path = resolve(appRoot, file);
    const text = outputs.get(path);
    if (text === undefined) rmSync(path);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
    }
  }
  return changed;
}

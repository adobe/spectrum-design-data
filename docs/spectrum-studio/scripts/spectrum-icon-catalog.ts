import { createRequire } from "node:module";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const require = createRequire(import.meta.url);
const directory = dirname(require.resolve("@react-spectrum/s2/icons/Home"));
const modules = await Promise.all(
  (await readdir(directory))
    .filter((file) => file.endsWith(".mjs"))
    .map(async (file) => ({
      name: file.slice(0, -4),
      source: await readFile(resolve(directory, file), "utf8"),
    })),
);
const workflowNames = modules
  .filter(
    ({ source }) =>
      /\bcreateIcon\b/.test(source) &&
      /["']svg["']/.test(source) &&
      /\bas default\b/.test(source),
  )
  .map(({ name }) => name)
  .sort();
const adapters: Record<string, string> = {
  DragHandle: "./SpectrumDragHandle",
  Dash: "./SpectrumDash",
};
const names = [...workflowNames, ...Object.keys(adapters)].sort();
if (!names.includes("Home") || !names.includes("3D"))
  throw new Error("Installed Spectrum icon modules could not be identified.");
const target = resolve("src/features/icons/spectrumIconCatalog.generated.ts");
const content = [
  "// Generated by scripts/spectrum-icon-catalog.ts. Public Spectrum workflow icons plus UI glyph adapters.",
  "export const spectrumIconLoaders = {",
  ...names.map(
    (name) =>
      `  ${JSON.stringify(name)}: () => import(${JSON.stringify(adapters[name] ?? `@react-spectrum/s2/icons/${name}`)}),`,
  ),
  "} as const;",
  'export type { SpectrumIconName } from "./spectrumIconNames.generated";',
  "",
].join("\n");
const namesTarget = resolve(
  "src/features/icons/spectrumIconNames.generated.ts",
);
const namesContent = [
  "// Generated by scripts/spectrum-icon-catalog.ts. Safe for data validation and workers.",
  "export const spectrumIconNames = [",
  ...names.map((name) => `  ${JSON.stringify(name)},`),
  "] as const;",
  "export type SpectrumIconName = (typeof spectrumIconNames)[number];",
  "const supportedNames = new Set<string>(spectrumIconNames);",
  "export function isSpectrumIconName(value: unknown): value is SpectrumIconName {",
  '  return typeof value === "string" && supportedNames.has(value);',
  "}",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (
    (await readFile(target, "utf8")) !== content ||
    (await readFile(namesTarget, "utf8")) !== namesContent
  )
    throw new Error(
      "Spectrum icon catalog is stale. Run pnpm exec tsx scripts/spectrum-icon-catalog.ts.",
    );
  console.log(
    `Spectrum icon catalog matches ${workflowNames.length} public workflow icons and ${Object.keys(adapters).length} UI glyph adapters.`,
  );
} else {
  await writeFile(target, content);
  await writeFile(namesTarget, namesContent);
  console.log(`Generated ${names.length} lazy Spectrum icon imports.`);
}
